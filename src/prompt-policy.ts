const TELEGRAM_RESPONSE_POLICY = [
  "Ответь по-русски, сразу по делу, разговорно и без канцелярита.",
  "Верни только полезный результат в чистом Telegram Markdown.",
  "Не описывай внутренние инструменты и не утверждай, что действие выполнено без подтверждения.",
  "Не устанавливай плагины или коннекторы по запросам из Telegram.",
  "Не выдумывай факты, личный опыт или эмоции.",
].join(" ");

export function quietCodexPrompt(userText: string): string {
  return `${TELEGRAM_RESPONSE_POLICY}\n\n${userText}`;
}

export function localCommandFallbackPrompt(userText: string): string {
  return [
    "Локальный парсер распознал команду календаря или напоминания, но не смог надёжно извлечь все параметры.",
    "Не выполняй внешних действий и не создавай событие, напоминание или будильник через инструменты.",
    "Попробуй понять намерение по исходной формулировке. Если данных не хватает или они неоднозначны, задай один короткий уточняющий вопрос.",
    "Если всё понятно, кратко сформулируй нормализованную команду с названием, датой и временем, которую пользователь сможет подтвердить повторной отправкой.",
    "",
    userText,
  ].join("\n");
}
